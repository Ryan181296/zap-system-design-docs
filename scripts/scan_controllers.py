#!/usr/bin/env python3
"""
ZAP Backend Java Controller Scanner & Git Commit Log Dynamic Extractor
Auto-generates docs/system-design/js/api-data.js
"""

import os
import re
import json
import subprocess
import urllib.request

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SYSTEM_DESIGN_DIR = os.path.dirname(SCRIPT_DIR)
WORKSPACE_ROOT = os.path.dirname(os.path.dirname(SYSTEM_DESIGN_DIR))
BACKEND_DIR = os.path.join(WORKSPACE_ROOT, "backend")
OUTPUT_FILE = os.path.join(SYSTEM_DESIGN_DIR, "js", "api-data.js")

SERVICES = [
    { "id": "all", "name": "All Services (Auto-Synced)", "icon": "⚡" },
    { "id": "gateway", "name": "API Gateway", "icon": "🌐", "port": 8080 },
    { "id": "identity", "name": "Identity Service", "icon": "🔐", "port": 8081 },
    { "id": "commerce", "name": "Commerce Service", "icon": "🛒", "port": 8082 },
    { "id": "payment", "name": "Payment Service", "icon": "💳", "port": 8083 },
    { "id": "notification", "name": "Notification Service", "icon": "🔔", "port": 8084 }
]

SECURITY_HEADERS = [
    { "name": "Authorization", "description": "JWT Access Token formatted as Bearer <token>", "required": True, "example": "Bearer eyJhbGciOiJIUzUx..." },
    { "name": "x-auth-signature", "description": "RSA 2048-bit digital signature generated by hardware chip (Secure Enclave / TEE)", "required": True, "example": "Base64SignatureString==" },
    { "name": "x-auth-timestamp", "description": "Unix epoch timestamp in milliseconds (max 5 min drift)", "required": True, "example": "1723205160000" },
    { "name": "x-auth-nonce", "description": "Cryptographic random nonce to prevent replay attacks", "required": True, "example": "nonce_a98f12" },
    { "name": "x-auth-checksum", "description": "SHA-256 hash digest of the raw HTTP request body", "required": True, "example": "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855" }
]

def get_service_id(filepath):
    for key in ["identity", "commerce", "payment", "notification", "gateway"]:
        if key in filepath.lower():
            return key, f"{key.capitalize()} Service"
    return "commerce", "Commerce Service"

def scan_git_commits():
    commit_activity = []
    repo_dirs = [("identity-service", "#10B981"), ("commerce-service", "#3B82F6"), ("payment-service", "#8B5CF6"), ("notification-service", "#F59E0B"), ("api-gateway", "#EC4899")]
    token = os.environ.get("BACKEND_REPO_TOKEN") or os.environ.get("GITHUB_TOKEN") or ""

    for repo_name, color in repo_dirs:
        target_dir = os.path.join(BACKEND_DIR, repo_name)
        recent_commits, total_cnt = [], 0

        if token:
            try:
                url = f"https://api.github.com/repos/Ryan181296/{repo_name}/commits?per_page=50"
                req = urllib.request.Request(url, headers={"Authorization": f"token {token}", "User-Agent": "Zap-System-Scanner", "Accept": "application/vnd.github.v3+json"})
                with urllib.request.urlopen(req, timeout=8) as resp:
                    if resp.status == 200:
                        for item in json.loads(resp.read().decode('utf-8')):
                            sha = item.get("sha", "")[:7]
                            ca = (item.get("commit") or {}).get("author") or {}
                            recent_commits.append({"hash": sha, "author": ca.get("name") or "dev-team", "msg": (item.get("commit") or {}).get("message", "").split("\n")[0], "date": ca.get("date", "")[:10]})
                        total_cnt = len(recent_commits)
            except Exception:
                pass

        if not recent_commits and os.path.exists(target_dir):
            try:
                cmd = ["git", "-C", target_dir, "log", "-n", "30", "--pretty=format:%h|%an|%s|%ad", "--date=short"]
                res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False)
                if res.returncode == 0 and res.stdout.strip():
                    for line in res.stdout.strip().split("\n"):
                        p = line.split("|")
                        if len(p) >= 4:
                            recent_commits.append({"hash": p[0], "author": p[1], "msg": p[2], "date": p[3]})
                    count_res = subprocess.run(["git", "-C", target_dir, "rev-list", "--count", "HEAD"], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False)
                    total_cnt = int(count_res.stdout.strip()) if count_res.returncode == 0 else len(recent_commits)
            except Exception:
                pass

        commit_activity.append({"name": repo_name, "total": total_cnt or max(12, len(recent_commits)), "color": color, "recent": recent_commits[:15]})
    return commit_activity

def parse_java_controller(filepath):
    endpoints = []
    svc_id, svc_name = get_service_id(filepath)
    with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
        content = f.read()

    base_path_match = re.search(r'@RequestMapping\s*\(\s*(?:value\s*=\s*)?["\']([^"\']+)["\']', content)
    base_path = base_path_match.group(1).rstrip('/') if base_path_match else ""

    methods = re.findall(r'@(GetMapping|PostMapping|PutMapping|DeleteMapping|PatchMapping)\s*(?:\(\s*(?:value\s*=\s*)?["\']([^"\']*)["\'])?', content)
    for m, p in methods:
        method = m.replace('Mapping', '').upper()
        clean_p = '/' + p.lstrip('/') if p else ""
        full_path = (base_path + clean_p) if (base_path or clean_p) else "/"
        ep_id = f"{svc_id}-{method.lower()}-{re.sub(r'[^a-zA-Z0-9]', '-', full_path).strip('-')}"
        endpoints.append({
            "id": ep_id, "serviceId": svc_id, "serviceName": svc_name, "method": method, "path": full_path,
            "summary": f"Endpoint {method} {full_path}", "description": f"Controller endpoint scanned from {os.path.basename(filepath)}"
        })
    return endpoints

def scan_all_controllers():
    all_endpoints = []
    if os.path.exists(BACKEND_DIR):
        for root, _, files in os.walk(BACKEND_DIR):
            for file in files:
                if file.endswith("Controller.java"):
                    all_endpoints.extend(parse_java_controller(os.path.join(root, file)))

    # Deduplicate
    unique = {}
    for ep in all_endpoints:
        k = f"{ep['method']}_{ep['path']}"
        if k not in unique:
            unique[k] = ep

    endpoints = list(unique.values())
    commits = scan_git_commits()

    data = {
        "services": SERVICES,
        "securityHeaders": SECURITY_HEADERS,
        "endpoints": endpoints,
        "commitActivity": commits
    }

    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
        f.write("// AUTO-GENERATED PARSED FROM JAVA CONTROLLERS\nconst ZAP_API_DATA = ")
        json.dump(data, f, indent=2)
        f.write(";\n")
    print(f"✅ Generated {OUTPUT_FILE} with {len(endpoints)} endpoints.")

if __name__ == "__main__":
    scan_all_controllers()
